const getLang = () => {
    const l = navigator.language.substring(0, 2);
    return bl_i18n[l] ? l : 'en';
};

const t = (key) => {
    return bl_i18n[getLang()][key] || bl_i18n['en'][key] || key;
};

// Auto-translate data-i18n elements on DOM load if we are in an HTML page
if (typeof document !== 'undefined') {
    document.addEventListener('DOMContentLoaded', () => {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (t(key) !== key) {
                // If it's an input/textarea, update placeholder, else textContent
                if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                    if (el.type === 'button' || el.type === 'submit') {
                        el.value = t(key);
                    } else {
                        el.placeholder = t(key);
                    }
                } else {
                    el.innerHTML = t(key);
                }
            }
        });
    });
}
